export function helpTextHtml(opts: { fullAccess: boolean }): string {
  const spreads = opts.fullAccess
    ? `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (граница суток — по дате в часовом поясе Москвы).  
• <b>Прошлое — настоящее — будущее</b> — три карты и связное толкование.`
    : `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (по дате в Москве).  
• Расклад «прошлое — настоящее — будущее» сейчас доступен только приглашённым пользователям, с Premium или по промокоду (в закрытом режиме доступа).`;

  return `<b>Водоворот</b> — толкование карт Таро в личке. Работает <b>только в личных сообщениях</b>.

<b>Команды</b>
/start — приветствие и кнопки  
/menu — снова показать кнопки раскладов  
/help — эта справка  
/last — повторить последний разбор (хранится недолго в этой переписке)  
/promo КОД — активировать одноразовый промокод Premium

<b>Расклады</b>
${spreads}

<b>Подписка на «карту дня»</b>
После разбора «на день» можно включить ежедневную отправку кнопкой «Присылать каждый день». Один раз в сутки — и на ручной запрос, и на рассылку.

<b>Важно</b>
${DISCLAIMER_HELP}`;
}

export function isPublicEntryCommand(text: string | undefined): boolean {
  if (!text) return false;
  const t = text.trim();
  return (
    /^\/start(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/menu(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/help(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/last(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/promo(?:@\S+)?(?:\s|$)/i.test(t)
  );
}
