export function helpTextHtml(opts: { fullAccess: boolean }): string {
  const spreads = opts.fullAccess
    ? `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (граница суток — по дате в часовом поясе Москвы).  
• <b>Прошлое — настоящее — будущее</b> — три карты и связное толкование.`
    : `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (по дате в Москве).  
• Расклад «прошлое — настоящее — будущее» сейчас доступен только приглашённым пользователям, с Premium или по промокоду (при активном списке ALLOWED_TELEGRAM_USER_IDS на сервере).`;

  return `<b>Водоворот</b> — бот с толкованием карт Таро. Работает <b>только в личных сообщениях</b> с ботом.

<b>Команды</b>
/start — приветствие и кнопки  
/menu — снова показать клавиатуру  
/help — эта справка  
/last — ещё раз прислать последнее толкование из памяти сессии (до перезапуска бота)  
/promo КОД — активировать одноразовый промокод Premium

<b>Расклады</b>
${spreads}

<b>Подписка на «карту дня»</b>
После успешного ручного гадания «на день» можно включить ежедневную автоматическую отправку кнопкой «Присылать каждый день» (время по умолчанию 09:00 в часовом поясе лимита суток, см. переменную DAY_DRAW_TIMEZONE на сервере). Лимит «один раз за сутки» общий для ручного и автоматического режима.

<b>Важно</b>
${DISCLAIMER_HELP}`;
}

export function isPublicEntryCommand(text: string | undefined): boolean {
  if (!text) return false;
  const t = text.trim();
  return (
    /^\/start(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/menu(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/help(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/last(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/promo(?:@\S+)?(?:\s|$)/i.test(t)
  );
}
