/**
 * Тексты бота: единый смысл для /start, /menu, /help и сообщений об ограничениях.
 */

export const ETHOS = 'Это не гарантия будущего, а повод присмотреться к себе и к картам.';

/** Короткий дисклеймер для справки и при необходимости в других местах. */
export const DISCLAIMER_HELP =
  'Толкование не заменяет консультацию врача, юриста или финансового специалиста и не обещает конкретных событий.';

export const ACCESS_DENIED_MESSAGE =
  'Эта функция сейчас доступна только приглашённым пользователям. Карту на день можно вытянуть кнопкой ниже (один раз за сутки по UTC). Если вы тестировщик — попросите владельца добавить ваш user id в ALLOWED_TELEGRAM_USER_IDS.';

export const DAY_LIMIT_MESSAGE =
  'Сегодняшняя карта дня уже была. Новая попытка — после полуночи по времени UTC (дата по Гринвичу).';

export function startTextFull(): string {
  return `Привет, я <b>Водоворот</b>. Ниже можно вытянуть карту на день или расклад «прошлое — настоящее — будущее». ${ETHOS}`;
}

export function startTextLimited(): string {
  return `Привет, я <b>Водоворот</b>. Сейчас ты можешь вытянуть <b>карту на день</b> — не чаще одного раза за календарные сутки по времени UTC. Расклад «прошлое — настоящее — будущее» пока доступен только приглашённым пользователям. ${ETHOS}`;
}

export function menuTextFull(): string {
  return 'Снова выбор расклада — те же две кнопки ниже.';
}

export function menuTextLimited(): string {
  return 'Снова кнопка «На день» ниже. Карту на день — не чаще одного раза за сутки UTC.';
}

export function helpTextHtml(opts: { fullAccess: boolean }): string {
  const spreads = opts.fullAccess
    ? `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (граница суток сейчас по UTC).  
• <b>Прошлое — настоящее — будущее</b> — три карты и связное толкование.`
    : `• <b>На день</b> — одна карта и толкование на день. Не чаще одного раза за календарные сутки (граница суток сейчас по UTC).  
• Расклад «прошлое — настоящее — будущее» сейчас доступен только приглашённым пользователям (при активном списке ALLOWED_TELEGRAM_USER_IDS на сервере).`;

  return `<b>Водоворот</b> — бот с толкованием карт Таро. Работает <b>только в личных сообщениях</b> с ботом.

<b>Команды</b>
/start — приветствие и кнопки  
/menu — снова показать клавиатуру  
/help — эта справка

<b>Расклады</b>
${spreads}

<b>Важно</b>
${DISCLAIMER_HELP}`;
}

export function isPublicEntryCommand(text: string | undefined): boolean {
  if (!text) return false;
  const t = text.trim();
  return (
    /^\/start(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/menu(?:@\S+)?(?:\s|$)/i.test(t) ||
    /^\/help(?:@\S+)?(?:\s|$)/i.test(t)
  );
}
