/**
 * Формат ответов толкования по бренд-гайду Водоворот → встраивается в промпты.
 * В Telegram: HTML, строки-метки без тире в конце (см. READING_SECTION_LABELS).
 */

/** Заголовки блоков толкования (ровно такая строка целиком, без тире в конце). */
export const READING_SECTION_LABELS: readonly string[] = [
  'О чём здесь речь',
  'Коротко о дне',
  'Прошлое',
  'Настоящее',
  'Будущее',
  'Как это сходится',
];

const SECTION_LABEL_SET = new Set(READING_SECTION_LABELS);

export function isReadingSectionLabelLine(line: string): boolean {
  return SECTION_LABEL_SET.has(line.trim());
}

/** Расклад «на день»; первая строка ответа = шапка карты из кода. */
export function brandFormatDayPromptBlock(cardHeadLine: string): string {
  return `ФОРМАТ ОТВЕТА (соблюдай буквально):
• Строка 1 только она: ${cardHeadLine}
• Пустая строка.
• Отдельная строка-метка ровно: О чём здесь речь
  Ниже 1–2 абзаца: объясни смысл карты на сегодня простым, понятным русским.
• Пустая строка.
• Отдельная строка-метка ровно: Коротко о дне
  Ниже ровно один абзац: короткий вывод дня, без списков дел и без «надо срочно».

Запрещено: другие заголовки, #, маркированные/нумерованные списки, текст перед первой меткой.
Не добавляй тире в конец строк меток; не используй символы < > & и не размечай текст звёздочками — оформление заголовков делает бот (полужирные метки в Telegram).
После блока «Коротко о дне» добавь пустую строку и один короткий финальный абзац (без новой метки): нейтрально напомни, что это повод поразмыслить, а не приговор и не жёсткая инструкция — одна фраза, без повторения этой мысли выше.`;
}

/** Расклад «прошлое — настоящее — будущее». */
export function brandFormatSpreadPromptBlock(): string {
  return `ФОРМАТ ОТВЕТА (соблюдай буквально):
• Сразу первый блок, без вступления.
• Порядок (каждая метка — отдельная строка, ровно как написано, без тире в конце):
  Прошлое
  Один абзац по карте; о положении пиши только если карта в этой позиции перевёрнутая.
  Пустая строка.
  Настоящее
  Один абзац (то же про ориентацию).
  Пустая строка.
  Будущее
  Один абзац (то же про ориентацию).
  Пустая строка.
  Как это сходится
  1–2 абзаца: связь трёх карт одним понятным текстом.

Запрещено: #, списки, любой текст до строки «Прошлое», упоминание маски-рассказчика отдельной строкой.
Не добавляй « —» к меткам; не используй < > & и звёздочки для «маркдауна» — разметку меток добавляет бот.
После блока «Как это сходится» добавь пустую строку и один короткий финальный абзац: размышление над картами не равно приговору и не заменяет твой выбор — сказать это спокойно, один раз, без морали в каждом абзаце выше.`;
}
