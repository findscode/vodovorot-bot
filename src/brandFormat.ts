/**
 * Формат ответов толкования по бренд-гайду Водоворот → встраивается в промпты.
 * В Telegram: HTML, строки-метки без тире в конце (см. READING_SECTION_LABELS).
 */

/** Заголовки блоков толкования (ровно такая строка целиком, без тире в конце). */
export const READING_SECTION_LABELS: readonly string[] = [
  'О чём здесь речь',
  'Коротко о дне',
  'Прошлое',
  'Настоящее',
  'Будущее',
  'Как это сходится',
];

const SECTION_LABEL_SET = new Set(READING_SECTION_LABELS);

export function isReadingSectionLabelLine(line: string): boolean {
  return SECTION_LABEL_SET.has(line.trim());
}

/**
 * Расклад «на день»: карта уже в подписи к фото (заголовок + строка карты от бота).
 * Ответ модели — только блоки меток, без дублирования строки карты перед «О чём здесь речь».
 */
export function brandFormatDayPromptBlock(): string {
  return `ФОРМАТ ОТВЕТА (соблюдай буквально):
Пользователь уже видит название карты и ориентацию в подписи к изображению выше — не повторяй их отдельной строкой перед метками.

• Отдельная строка-метка ровно: О чём здесь речь
  Ниже 1–2 абзаца: объясни смысл карты на сегодня простым, понятным русским.

Между абзацем под «О чём здесь речь» и следующей меткой — одна пустая строка (никакого текста на ней, не пиши на ней слова вроде «пустая строка»).

• Отдельная строка-метка ровно: Коротко о дне
  Ниже ровно один абзац: короткий вывод дня, без списков дел и без «надо срочно».

Между абзацем под «Коротко о дне» и финальным абзацем — снова одна пустая строка без текста.

Запрещено: другие заголовки, #, маркированные/нумерованные списки, текст перед первой меткой «О чём здесь речь», любые служебные фразы про вёрстку («пустая строка», «новый абзац» и т.п.) — только живой текст толкования.
Не добавляй тире в конец строк меток; не используй символы < > & и не размечай текст звёздочками — оформление заголовков делает бот (полужирные метки в Telegram).
После блока «Коротко о дне» и пустой строки добавь один короткий финальный абзац (без новой метки): нейтрально напомни, что это повод поразмыслить, а не приговор и не жёсткая инструкция — одна фраза, без повторения этой мысли выше.`;
}

/**
 * Расклад «прошлое — настоящее — будущее»: позиции и карты уже в подписи к коллажу.
 */
export function brandFormatSpreadPromptBlock(): string {
  return `ФОРМАТ ОТВЕТА (соблюдай буквально):
Три позиции и названия карт пользователь уже видит в подписи к коллажу выше — не дублируй их шапкой перед первой меткой.

• Порядок (каждая метка — отдельная строка, ровно как написано, без тире в конце):
  Прошлое
  Один абзац по карте; о положении пиши только если карта в этой позиции перевёрнутая.

После этого абзаца — одна пустая строка без какого-либо текста (не пиши на ней «пустая строка» и аналоги).

  Настоящее
  Один абзац (то же про ориентацию).

Снова одна пустая строка без текста.

  Будущее
  Один абзац (то же про ориентацию).

Снова одна пустая строка без текста.

  Как это сходится
  1–2 абзаца: связь трёх карт одним понятным текстом.

Запрещено: #, списки, любой текст до строки «Прошлое», упоминание маски-рассказчика отдельной строкой, служебные фразы про разметку («Пустая строка.», «пустая строка» и т.д.).
Не добавляй « —» к меткам; не используй < > & и звёздочки для «маркдауна» — разметку меток добавляет бот.
После блока «Как это сходится» добавь одну пустую строку без текста и один короткий финальный абзац: размышление над картами не равно приговору и не заменяет твой выбор — сказать это спокойно, один раз, без морали в каждом абзаце выше.`;
}
