import { describe, expect, it } from 'vitest';
import {
  isAutoGeneratedPromoShape,
  normalizePromoCode,
  parsePromoCodeFromUserText,
} from './promoInput.js';

describe('promoInput', () => {
  it('normalizePromoCode trims and uppercases', () => {
    expect(normalizePromoCode('  star-lantern-k7np4x  ')).toBe('STAR-LANTERN-K7NP4X');
  });

  it('strips invisible chars before /promo', () => {
    const zw = '\u200B';
    expect(parsePromoCodeFromUserText(`${zw}/promo STAR-LANTERN-K7NP4X`)).toBe(
      'STAR-LANTERN-K7NP4X',
    );
  });

  it('parses /promo and /promo@bot', () => {
    expect(parsePromoCodeFromUserText('/promo STAR-LANTERN-K7NP4X')).toBe('STAR-LANTERN-K7NP4X');
    expect(parsePromoCodeFromUserText('/promo@VodovorotBot STAR-LANTERN-K7NP4X')).toBe(
      'STAR-LANTERN-K7NP4X',
    );
  });

  it('accepts plain auto-generated code on one line', () => {
    expect(parsePromoCodeFromUserText('STAR-LANTERN-K7NP4X')).toBe('STAR-LANTERN-K7NP4X');
  });

  it('rejects short manual codes without /promo', () => {
    expect(parsePromoCodeFromUserText('TEST-ONCE')).toBeNull();
    expect(parsePromoCodeFromUserText('/promo TEST-ONCE')).toBe('TEST-ONCE');
  });

  it('isAutoGeneratedPromoShape checks secret suffix', () => {
    expect(isAutoGeneratedPromoShape('STAR-LANTERN-K7NP4X')).toBe(true);
    expect(isAutoGeneratedPromoShape('TEST-ONCE')).toBe(false);
  });
});
