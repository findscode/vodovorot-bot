import { PROMO_SECRET_ALPHABET, PROMO_SECRET_LENGTH } from './promoConfig.js';

/** Невидимые символы при копировании из Telegram (HTML, мобильный клиент). */
const INVISIBLE_CHARS = /[\u200B-\u200D\uFEFF\u00AD]/g;

export function stripInvisibleForPromo(text: string): string {
  return text.replace(INVISIBLE_CHARS, '');
}

/** Нормализация сырого кода (без префикса /promo). */
export function normalizePromoCode(raw: string): string | null {
  const code = stripInvisibleForPromo(raw).trim().toUpperCase();
  if (!code || code.length > 64) return null;
  if (!/^[A-Z0-9][A-Z0-9_-]*$/.test(code)) return null;
  return code;
}

/** Автогенерируемый код: таро-префикс + секрет {@link PROMO_SECRET_LENGTH}. */
export function isAutoGeneratedPromoShape(code: string): boolean {
  const parts = code.split('-');
  if (parts.length < 2) return false;
  const secret = parts[parts.length - 1]!;
  if (secret.length !== PROMO_SECRET_LENGTH) return false;
  for (const c of secret) {
    if (!PROMO_SECRET_ALPHABET.includes(c)) return false;
  }
  return true;
}

/**
 * Извлекает промокод из сообщения: /promo КОД, /promo@bot КОД или одна строка с автокодом.
 */
export function parsePromoCodeFromUserText(text: string): string | null {
  const t = stripInvisibleForPromo(text).trim();
  if (!t || t.includes('\n')) return null;

  const cmd = t.match(/^\/promo(?:@\S+)?\s+(.+)$/i);
  const payload = cmd ? cmd[1]!.trim() : t;
  const code = normalizePromoCode(payload);
  if (!code) return null;
  if (cmd) return code;
  return isAutoGeneratedPromoShape(code) ? code : null;
}
