import type { TarotCard } from './deck.js';

/**
 * Слой «голоса гадания»: архетип-рассказчик задаёт маску, от которой ведётся толкование.
 * Не путать с выпавшими в раскладе картами — это отдельный случайный выбор из старших арканов.
 */
export function promptVoiceArchetypeBlock(voice: TarotCard): string {
  return `Внутренний голос толкования — образ «${voice.name}» (старший аркан как невидимая маска).
Пиши так, как мог бы смотреть на карты этот архетип: акценты и образы в духе его природы, но формулировки остаются понятными обычному читателю — без намеренной запутанности. Не объясняй, что «ты в роли»; не называй маску в первых строках ответа.
Тон спокойный: без лести, без крика, без давления «сделай так-то».`;
}
